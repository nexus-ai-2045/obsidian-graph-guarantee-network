#Requires -Version 5.1

# Optional audit reports: JSON for agents, Markdown for people, and an Obsidian
# Bases view. Only written when the audit is given -ReportDirectory.
# Loaded by obsidian-graph-network-lib.ps1. Do not dot-source this file on its own.

$script:GraphNetReportJsonName = 'graph-audit.json'
$script:GraphNetReportMarkdownName = 'graph-audit.md'
$script:GraphNetReportBaseName = 'graph-audit.base'
$script:GraphNetReportSchema = 'obsidian-graph-audit/v1'

function Write-GraphNetReportFile {
  param(
    [string]$Path,
    [string]$Content
  )

  # Compare-then-write with LF newlines and no-BOM UTF-8, so an unchanged vault
  # rewrites nothing and the report stays byte-identical across reruns.
  $encoding = [System.Text.UTF8Encoding]::new($false)
  $normalized = ($Content -replace "`r`n", "`n")
  if (-not $normalized.EndsWith("`n")) {
    $normalized += "`n"
  }
  if (Test-Path -LiteralPath $Path -PathType Leaf) {
    if ([System.IO.File]::ReadAllText($Path, $encoding) -ceq $normalized) {
      return $false
    }
  }
  [System.IO.File]::WriteAllText($Path, $normalized, $encoding)
  return $true
}

function Format-GraphNetCodeSpan {
  param([string]$Text)

  # Render a note path as inline code, never as a link, so the report does not
  # add edges to the Obsidian graph it describes.
  $fence = '`'
  while ($Text.Contains($fence)) {
    $fence += '`'
  }
  if ($fence.Length -gt 1) {
    return ($fence + ' ' + $Text + ' ' + $fence)
  }
  return ($fence + $Text + $fence)
}

function Get-GraphNetAuditReportData {
  param(
    [pscustomobject]$Summary,
    [string[]]$Orphans = @(),
    [object[]]$Components = @(),
    [object[]]$UnresolvedDetails = @(),
    [int]$SmallIslandMaxSize = 5
  )

  # Deterministic report payload. It carries no absolute vault path and no
  # timestamp, so the same vault always yields the same bytes.
  # A component larger than SmallIslandMaxSize is treated as a main body of
  # notes; every component of 2..SmallIslandMaxSize notes is a small island.
  $islands = @($Components | Where-Object { ($_.Size -ge 2) -and ($_.Size -le $SmallIslandMaxSize) })
  $unresolved = @($UnresolvedDetails | Sort-Object -Property @{ Expression = 'Source' }, @{ Expression = 'Target' }, @{ Expression = 'Reason' } | ForEach-Object {
    [ordered]@{ source = $_.Source; target = $_.Target; reason = $_.Reason }
  })

  return [ordered]@{
    schema = $script:GraphNetReportSchema
    summary = [ordered]@{
      coveredNotes = $Summary.CoveredNotes
      orphanNotes = $Summary.OrphanNotes
      nativeConnectedComponents = $Summary.NativeConnectedComponents
      largestComponentSize = $Summary.LargestComponentSize
      nativeDegreeMin = $Summary.NativeDegreeMin
      nativeDegreeMedian = $Summary.NativeDegreeMedian
      nativeDegreeMax = $Summary.NativeDegreeMax
      unresolvedLinks = $Summary.UnresolvedLinks
    }
    orphans = @($Orphans)
    smallIslandMaxSize = $SmallIslandMaxSize
    smallIslands = @($islands | ForEach-Object { , @($_.Members) })
    unresolvedLinks = $unresolved
  }
}

function ConvertTo-GraphNetAuditMarkdown {
  param([System.Collections.IDictionary]$Data)

  $lines = [System.Collections.Generic.List[string]]::new()
  $summary = $Data.summary
  $lines.Add('# Graph audit')
  $lines.Add('')
  $lines.Add('Generated by the read-only audit of obsidian-graph-guarantee-network. Note paths are shown as code, not links, so this report adds no edges to the graph it describes. Rerun the audit to refresh it.')
  $lines.Add('')
  $lines.Add('## Summary')
  $lines.Add('')
  $lines.Add('| Metric | Value |')
  $lines.Add('|---|---|')
  $lines.Add(('| Covered notes | {0} |' -f $summary.coveredNotes))
  $lines.Add(('| Orphan notes (no native links) | {0} |' -f $summary.orphanNotes))
  $lines.Add(('| Connected components | {0} |' -f $summary.nativeConnectedComponents))
  $lines.Add(('| Largest component | {0} |' -f $summary.largestComponentSize))
  $lines.Add(('| Degree min / median / max | {0} / {1} / {2} |' -f $summary.nativeDegreeMin, $summary.nativeDegreeMedian, $summary.nativeDegreeMax))
  $lines.Add(('| Unresolved or ambiguous links | {0} |' -f $summary.unresolvedLinks))
  $lines.Add('')
  $lines.Add('## How to use this report')
  $lines.Add('')
  $lines.Add('1. For each orphan, add one link from a note it belongs with, or list it in a map-of-content note for its topic.')
  $lines.Add('2. Join each small island to the main body of notes with one meaningful link.')
  $lines.Add('3. Fix unresolved links: create the missing note, correct the name, or use a path when a name is shared by several notes.')
  $lines.Add('4. Open `graph-audit.base` in Obsidian for live lists of notes with no backlinks or no outgoing links.')
  $lines.Add('')
  $lines.Add(('## Orphans ({0})' -f @($Data.orphans).Count))
  $lines.Add('')
  if (@($Data.orphans).Count -eq 0) {
    $lines.Add('None.')
  } else {
    foreach ($orphan in $Data.orphans) {
      $lines.Add('- ' + (Format-GraphNetCodeSpan -Text $orphan))
    }
  }
  $lines.Add('')
  $lines.Add(('## Small islands (2 to {0} notes, {1})' -f $Data.smallIslandMaxSize, @($Data.smallIslands).Count))
  $lines.Add('')
  if (@($Data.smallIslands).Count -eq 0) {
    $lines.Add('None.')
  } else {
    $index = 0
    foreach ($island in $Data.smallIslands) {
      $index++
      $lines.Add(('- Island {0}: {1}' -f $index, ((@($island) | ForEach-Object { Format-GraphNetCodeSpan -Text $_ }) -join ', ')))
    }
  }
  $lines.Add('')
  $lines.Add(('## Unresolved or ambiguous links ({0})' -f @($Data.unresolvedLinks).Count))
  $lines.Add('')
  if (@($Data.unresolvedLinks).Count -eq 0) {
    $lines.Add('None.')
  } else {
    $lines.Add('| From | Target | Reason |')
    $lines.Add('|---|---|---|')
    foreach ($entry in $Data.unresolvedLinks) {
      $lines.Add(('| {0} | {1} | {2} |' -f (Format-GraphNetCodeSpan -Text ($entry.source -replace '\|', '\|')), (Format-GraphNetCodeSpan -Text ($entry.target -replace '\|', '\|')), $entry.reason))
    }
  }
  return ($lines -join "`n")
}

function ConvertTo-GraphNetAuditBase {
  param([string[]]$ExcludedFolders = @())

  # An Obsidian Bases file (core plugin, Obsidian 1.9+) with two live views.
  # file.backlinks is documented as performance heavy and not auto-refreshing,
  # so the orphan view is a starting point and this audit stays the measure.
  $lines = [System.Collections.Generic.List[string]]::new()
  $lines.Add('filters:')
  $lines.Add('  and:')
  $lines.Add("    - 'file.ext == ""md""'")
  foreach ($folder in @($ExcludedFolders | Where-Object { -not [string]::IsNullOrWhiteSpace($_) } | Sort-Object -Unique)) {
    $escaped = $folder.Replace('\', '/').Replace('"', '\"').Replace("'", "''")
    $lines.Add(("    - '!file.inFolder(""{0}"")'" -f $escaped))
  }
  $lines.Add('views:')
  $lines.Add('  - type: table')
  $lines.Add('    name: No backlinks')
  $lines.Add('    filters:')
  $lines.Add('      and:')
  $lines.Add("        - 'file.backlinks.isEmpty()'")
  $lines.Add('    order:')
  $lines.Add('      - file.name')
  $lines.Add('      - file.path')
  $lines.Add('  - type: table')
  $lines.Add('    name: No outgoing links')
  $lines.Add('    filters:')
  $lines.Add('      and:')
  $lines.Add("        - 'file.links.isEmpty()'")
  $lines.Add('    order:')
  $lines.Add('      - file.name')
  $lines.Add('      - file.path')
  return ($lines -join "`n")
}
